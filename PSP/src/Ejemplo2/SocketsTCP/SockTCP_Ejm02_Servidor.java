package Ejemplo2.SocketsTCP;

import java.io.BufferedReader;
import java.io.BufferedWriter;
import java.io.IOException;
import java.io.InputStreamReader;
import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import java.net.ServerSocket;
import java.net.Socket;

/**
 * Class Server. Waits for clients connections. When a client
 * connects to it, they will exchange information until the client
 * sends the keyword END. As soon as this happends,
 * the connection closes and execution ends.
 * @author: ...
 * @mailto ...
*/ 
public class SockTCP_Ejm02_Servidor {
  /**
   * An available port greater than 1024 is selected
  */
  public static final int PORT = 8080;
  
  public static void main(String[] args) throws IOException{
	ServerSocket server = new ServerSocket(PORT);
	Socket socket = null;
	System.out.println("Started: " + server);
	try {
	  //Blocked until a connection happends
	  socket = server.accept();
	  System.out.println("Connection accepted: " + socket);
	  BufferedReader input
	    = new BufferedReader(
		    new InputStreamReader(
			    socket.getInputStream()));
	  //The output usually is generated by a PrintWriter
	  PrintWriter output;
	  output = new PrintWriter(
		new BufferedWriter(
			new OutputStreamWriter(
				socket.getOutputStream())),
			true);
	  while (true) {
	    String str = input.readLine();
		if (str.equals("END")) {
		  break;
		}
		System.out.println("Printing input: " + str);
		output.println(str);
	  }
	//Always close both sockets...
	} finally {
	  System.out.print("Closing...");
	  socket.close();
	  server.close();
	}
  }
}